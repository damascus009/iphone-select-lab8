"""Generate progressive-enhancement cards and offline snapshot from data.json only."""
from pathlib import Path
import json,html,sys
from bs4 import BeautifulSoup
root=Path(__file__).resolve().parent.parent
data=json.loads((root/'data.json').read_text());products=data['products'];esc=html.escape
snapshot='// Generated by scripts/generate-catalog.py from data.json; do not edit.\nexport const catalog = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'
s=BeautifulSoup((root/'catalog.html').read_text(),'html.parser')
container=s.select_one('.model-card').parent
cards=[]
for p in products:
 cards.append(f'''<article class="model-card" data-model="{esc(p['name'].lower())}" data-product-id="{p['id']}"><p class="model-family">{esc(p['chip'])} · OLED {p['display']}″</p><h2>{esc(p['name'])}</h2><ul>{''.join('<li>'+esc(x)+'</li>' for x in p['features'])}</ul><p class="model-colors">Кольори: {esc(', '.join(p['colors']))}</p><a href="{p['source']}" target="_blank" rel="noopener noreferrer">Характеристики Apple <span class="sr-only">{esc(p['name'])} (нова вкладка)</span> ↗</a><p class="model-price">Ціну й наявність не підтверджено</p><div class="model-actions"><button type="button" data-configure="{p['id']}">Налаштувати<span class="sr-only"> {esc(p['name'])}</span></button><button type="button" data-add-cart>У кошик<span class="sr-only"> {esc(p['name'])}</span></button></div></article>''')
container.clear();container['class']=['model-grid'];container['id']='model-grid'
for c in cards:container.append(BeautifulSoup(c,'html.parser'))
# Comparison remains available without JS, and filters alongside the cards.
table=s.select_one('#comparison table')
if table:
 table.clear();table.append(BeautifulSoup('<caption>Моделі з офіційно перевіреними характеристиками Apple</caption><thead><tr><th scope="col">Модель</th><th scope="col">Екран OLED</th><th scope="col">Чип</th><th scope="col">Пам’ять</th></tr></thead><tbody>'+''.join(f'<tr data-compare-model="{p["id"]}"><th scope="row">{p["name"]}</th><td>{p["display"]}″</td><td>{p["chip"]}</td><td>{p["features"][2]}</td></tr>' for p in products)+'</tbody>','html.parser'))
for select in s.select('#model-filter,#config-model,#trade-model'):
 select.clear();select.append(BeautifulSoup('<option value="">'+('Усі моделі' if select['id']=='model-filter' else 'Оберіть модель')+'</option>'+''.join(f'<option value="{p["id"]}">{p["name"]}</option>' for p in products),'html.parser'))
suggestions=s.select_one('#model-options')
if suggestions:
 suggestions.clear();suggestions.append(BeautifulSoup('<option value="iPhone 18 Pro">Концепт проєкту</option>'+''.join(f'<option value="{esc(p["name"])}"></option>' for p in products),'html.parser'))
outputs={root/'assets/js/catalog-snapshot.mjs':snapshot,root/'catalog.html':str(s)}
if '--check' in sys.argv:
 for path,value in outputs.items():
  if path.read_text()!=value:raise SystemExit('Stale generated file: '+str(path))
 print('Catalog snapshot, cards, selectors and comparison match data.json')
else:
 for path,value in outputs.items():path.write_text(value)
