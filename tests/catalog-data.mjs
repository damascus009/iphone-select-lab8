import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { validateCatalog, loadCatalog } from '../assets/js/catalog-data.mjs';
const data = JSON.parse(await readFile(new URL('../data.json', import.meta.url)));
assert.equal(validateCatalog(data).length, 2);
for (const bad of [null, {}, {...data, version:2}, {...data, products:[data.products[0],data.products[0]]}, {...data, products:[{...data.products[0], features:[null]},data.products[1]]}]) assert.throws(() => validateCatalog(bad));
assert.deepEqual(await loadCatalog(async () => ({ok:true,json:async()=>data})),data.products);
await assert.rejects(loadCatalog(async () => ({ok:false})));
await assert.rejects(loadCatalog(async () => {throw new Error('Offline');}));
await assert.rejects(loadCatalog(async () => ({ok:true,json:async()=>{throw new Error('Bad JSON');}})));
console.log('PASS catalog: valid data, duplicate/malformed products, HTTP error, offline, invalid JSON');
